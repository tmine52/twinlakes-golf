/** 用語の分類（並べる順） */
const GL_KINDS = ["スコア", "コース", "ショット", "ミス・球筋", "クラブ", "ルール・マナー", "アプリの言葉"];

/** 覚えた用語の数 */
function glKnown() {
  return GLOSSARY.filter((g) => R.gl && R.gl[g[0]]).length;
}

/** 選んでいる分類の用語 */
function glList() {
  return GLOSSARY.filter((g) => !U.gk || g[2] === U.gk);
}

/** 次に覚える用語（まだ覚えていないものから、順番に。全部覚えたら最初から） */
function glNext(after) {
  const l = glList(),
    todo = l.filter((g) => !(R.gl && R.gl[g[0]])),
    pool = todo.length ? todo : l,
    i = after ? pool.findIndex((g) => g[0] === after) : -1;
  return pool.length ? pool[(i + 1) % pool.length][0] : null;
}

/** 「コーチ → 用語」の画面 */
function glossaryView() {
  const mode = U.gm || "card",
    k = glKnown();
  let h =
    '<section class="card"><div class="h">ゴルフ用語</div>' +
    '<p class="note">覚えた用語 ' +
    k +
    " / " +
    GLOSSARY.length +
    '</p><div class="glbar"><div style="width:' +
    Math.round((k / GLOSSARY.length) * 100) +
    '%"></div></div>' +
    subTabs(
      [
        ["card", "覚える"],
        ["list", "一覧・さがす"],
      ],
      "gm",
      mode,
    ) +
    '<select class="input" data-gk style="margin-top:8px" aria-label="用語の分類"><option value="">すべての分類（' +
    GLOSSARY.length +
    "）</option>" +
    GL_KINDS.map(
      (x) =>
        '<option value="' +
        x +
        '"' +
        (U.gk === x ? " selected" : "") +
        ">" +
        x +
        "（" +
        GLOSSARY.filter((g) => g[2] === x).length +
        "）</option>",
    ).join("") +
    "</select></section>";
  return h + (mode === "list" ? glListCard() : glCard());
}

/** 覚える：1枚ずつ用語を出し、意味を思い出してから見る */
function glCard() {
  const l = glList();
  if (!l.length) return "";
  if (!U.gc || !l.some((g) => g[0] === U.gc)) U.gc = glNext();
  const g = GLOSSARY.find((x) => x[0] === U.gc),
    known = R.gl && R.gl[g[0]],
    left = l.filter((x) => !(R.gl && R.gl[x[0]])).length;
  return (
    '<section class="card glcard"><div class="note">' +
    esc(g[2]) +
    (known ? "・覚えた" : "") +
    "　この分類で、まだ覚えていない用語 " +
    left +
    '</div><div class="glterm" id="glterm">' +
    esc(g[0]) +
    '</div><div class="note">' +
    esc(g[1]) +
    "</div>" +
    (U.gshow
      ? '<p class="glmean">' +
        esc(g[3]) +
        "</p>" +
        (g[4] ? '<p class="note">アプリ・レッスンでは：' + esc(g[4]) + "</p>" : "") +
        '<div class="row2"><button class="ghost" data-gknow="0">まだ</button><button class="act" data-gknow="1">覚えた</button></div>'
      : '<p class="note">意味を思い出してから押してください。</p><button class="act" data-gshow style="width:100%">意味を見る</button>') +
    "</section>"
  );
}

/** 一覧・さがす：用語と意味の一覧。上の欄に入れた文字で、その場で絞り込む */
function glListCard() {
  return (
    '<section class="card"><input class="input" data-gq type="search" placeholder="用語や意味でさがす（例：ダフ、OB）" value="' +
    esc(U.gq || "") +
    '" aria-label="用語をさがす"><p class="note" id="glcount"></p>' +
    glList()
      .map(
        (g) =>
          '<div class="glitem" data-gtext="' +
          esc((g[0] + g[1] + g[3] + g[4]).toLowerCase()) +
          '"><div class="glh"><b>' +
          esc(g[0]) +
          '</b><button class="' +
          (R.gl && R.gl[g[0]] ? "act" : "ghost") +
          '" data-gmark="' +
          esc(g[0]) +
          '" aria-pressed="' +
          !!(R.gl && R.gl[g[0]]) +
          '">' +
          (R.gl && R.gl[g[0]] ? "覚えた" : "まだ") +
          '</button></div><div class="note">' +
          esc(g[1]) +
          "・" +
          esc(g[2]) +
          "</div><p>" +
          esc(g[3]) +
          "</p>" +
          (g[4] ? '<p class="note">アプリ・レッスンでは：' + esc(g[4]) + "</p>" : "") +
          "</div>",
      )
      .join("") +
    "</section>"
  );
}

/** さがす欄に入れた文字で、一覧をその場で絞り込む（画面を作り直さないので、入力中の文字が消えない） */
function glFilter() {
  const q = (U.gq || "").trim().toLowerCase(),
    items = [...document.querySelectorAll(".glitem")];
  let n = 0;
  items.forEach((e) => {
    const hit = !q || e.dataset.gtext.includes(q);
    e.hidden = !hit;
    if (hit) n++;
  });
  const c = document.getElementById("glcount");
  if (c) c.textContent = q ? n + "件 見つかりました" : n + "件";
}
