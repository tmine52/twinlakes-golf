/** 「11/22（日）」の形 */
function lsDay(l) {
  const m = /^\d{4}-(\d{2})-(\d{2})$/.exec(l.d);
  return (m ? Number(m[1]) + "/" + Number(m[2]) : l.d) + "（" + l.w + "）";
}

/** 「コーチ → レッスン」の画面：レッスンごとに、良かった点・言われたこと・次に意識することを並べる（新しい順） */
function coachLessons() {
  const list = (a) =>
    '<ul style="margin:4px 0 8px;padding-left:20px;line-height:1.6">' +
    a.map((x) => "<li>" + esc(x) + "</li>").join("") +
    "</ul>";
  return (
    '<section class="card"><div class="h">レッスンの振り返り</div><p class="note">レッスンごとに、コーチに言われたことを新しい順に並べています。次のレッスンの前に「次に意識すること」を見直してください。これより前のレッスン（10/25・11/01・11/08）の内容は「基本」にまとめてあります。</p></section>' +
    LESSONS.map(
      (l, i) =>
        '<section class="card lesson"><details' +
        (i === 0 ? " open" : "") +
        "><summary><b>" +
        esc(lsDay(l)) +
        "</b>　" +
        esc(l.who) +
        '</summary><p class="note">' +
        esc(l.src) +
        "</p>" +
        '<div class="lsnext"><div class="h">次に意識すること</div>' +
        list(l.next) +
        "</div>" +
        (l.good.length ? '<div class="t">良かった点</div>' + list(l.good) : "") +
        l.topics.map((t) => '<div class="t">' + esc(t[0]) + "</div>" + list(t[1])).join("") +
        (l.memo ? '<p class="note">' + esc(l.memo) + "</p>" : "") +
        "</details></section>",
    ).join("")
  );
}
